import { describe, it, expect, beforeEach } from 'vitest';
import { LatestEntryFinder } from '@/modules/finance/application/services/latest-entry-finder';
import { buildFakeEntryServices } from '@/tests/fakes/build-fake-entry-services';

describe('LatestEntryFinder', () => {
  let services: ReturnType<typeof buildFakeEntryServices>;
  let finder: LatestEntryFinder;

  beforeEach(() => {
    services = buildFakeEntryServices();
    finder = new LatestEntryFinder(services.transactionRepo, services.incomeRepo, services.investmentRepo);
  });

  const register = (description: string, fixed?: { fixedEntryId: string; referenceMonth: string }) =>
    services.registerEntry.execute(
      'user-1',
      { type: 'expense', category: 'Mercado', description, amount: 40, date: '2026-03-10' },
      fixed ? { fixed } : undefined
    );

  it('skips the entry generated by a fixed rule and returns the previous manual one', async () => {
    await register('Feira');
    await register('Internet', { fixedEntryId: 'fx-1', referenceMonth: '2026-03' });

    const latest = await finder.find('user-1');

    expect(latest?.description).toBe('Feira');
  });

  it('skips fixed incomes', async () => {
    await services.registerEntry.execute(
      'user-1',
      { type: 'income', category: 'Salário', description: 'Salário', amount: 5000, date: '2026-03-05' },
      { fixed: { fixedEntryId: 'fx-2', referenceMonth: '2026-03' } }
    );

    expect(await finder.find('user-1')).toBeNull();
  });

  it('skips imported incomes', async () => {
    await services.registerEntry.execute('user-1', {
      type: 'income',
      category: 'Salário',
      description: 'Pix',
      amount: 90,
      date: '2026-03-05',
    });
    services.incomeRepo.items[0].externalId = 'ext-1';

    expect(await finder.find('user-1')).toBeNull();
  });
});
